"""Generate the cloud schema from the current SQLite schema and migrations."""
import re
import sqlite3
import tempfile
from contextlib import closing
from pathlib import Path
from src.database.connection import init_db
from src.config import DATA_DIR

with tempfile.TemporaryDirectory() as directory:
    path = str(Path(directory) / 'schema.db')
    init_db(path)
    with closing(sqlite3.connect(path)) as connection:
        statements = [row[0] for row in connection.execute("SELECT sql FROM sqlite_master WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%' ORDER BY rowid")]
    result = []
    for sql in statements:
        sql = re.sub(r'INTEGER PRIMARY KEY AUTOINCREMENT', 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY', sql, flags=re.I)
        sql = re.sub(r'\s+COLLATE NOCASE', '', sql, flags=re.I)
        sql = re.sub(r'\bREAL\b', 'DOUBLE PRECISION', sql)
        sql = re.sub(r'^CREATE TABLE (?!IF NOT EXISTS)', 'CREATE TABLE IF NOT EXISTS ', sql)
        sql = re.sub(r'^CREATE INDEX (?!IF NOT EXISTS)', 'CREATE INDEX IF NOT EXISTS ', sql)
        result.append(sql + ';')
    (DATA_DIR / 'schema-postgres.sql').write_text('-- Generated by scripts/build-postgres-schema.py\n' + '\n\n'.join(result) + '\n', encoding='utf-8')
    print(f'Generated {len(result)} Postgres table/index statements.')
